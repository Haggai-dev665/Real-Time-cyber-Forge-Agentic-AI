/* The evidence report (DET-04): built by the backend from a fixed snapshot of the
   account's findings, incidents and stored evidence, signed, with what limits it.
   No language model writes any of it. */
async function buildEvidenceReport(range){
  if(genBtn.disabled)return;genBtn.disabled=true;genBtn.classList.add('busy');
  const now=new Date(), from=new Date(now.getTime()-range.sec*1000);
  const tz=(Intl.DateTimeFormat().resolvedOptions().timeZone)||'UTC';
  currentReport={ title:'Evidence Report — '+range.label, id:'EVR-'+Date.now(), date:now.toISOString().slice(0,10), at:now, range:range.label,classification:selectedClassification };
  sections=[];setDocHeader();
  document.getElementById('doc').classList.add('gen');
  setDocStatus('Building the evidence report…','From your account\'s findings, incidents and stored evidence for this period.');
  try{
    const d=await CF.invoke('evidence_report',{from:from.toISOString(),to:now.toISOString(),tz:tz});
    const r=d.report, L=r.limits;currentReport.kind='Evidence report';currentReport.evidence=d;setDocHeader();
    const sev=s=>s==='critical'?'crit':(s==='high'?'high':(s==='low'?'low':'med'));
    const list=(rows,empty)=>rows.length?rows.map(x=>'- '+x).join('\n'):empty;
    sections=[
      {type:'md',h:'Summary',body:list(r.summary,'')},
      {type:'md',h:'Period',body:'From '+r.window.fromLocal+' to '+r.window.toLocal+' ('+r.window.tz+').'},
      {type:'finds',h:'Findings',body:r.findings.map(f=>[sev(f.severity),f.type,f.status.replace(/_/g,' ')+' · seen '+f.occurrences+'× · last '+f.lastSeenLocal+(f.evidenceIds.length?(' · evidence '+f.evidenceIds.join(', ')):' · no stored evidence')])},
      {type:'md',h:'Incidents',body:list(r.incidents.map(i=>i.host+': '+i.state+', '+i.severity+', '+i.findings+' finding'+(i.findings===1?'':'s')+(i.evidenceIds.length?(', evidence '+i.evidenceIds.join(', ')):'')),'No incident in this period.')},
      {type:'md',h:'Evidence appendix',body:list(r.evidence.map(e=>e.id+' — '+e.target+' — '+e.verdict+' — collected '+e.collectedAt+' — sha256 '+e.evidenceHash+(e.intact?' — intact':' — CHANGED since collection')),'No stored evidence in this period.')},
      {type:'md',h:'Limits of this report',body:list([].concat(
        L.deletedEvidence.map(x=>'Deleted: '+x.resource+' at '+x.deletedAt+(x.evidenceHash?(' (sha256 '+x.evidenceHash+')'):'')),
        L.scansWithoutVerdict.map(x=>'No verdict: scan '+x),
        L.providerFailures.map(x=>'Did not run: '+x.tool+' in run '+x.runId+' — '+x.summary),
        L.devicesNotFullyCovered.map(x=>'Device '+x.displayName+': '+x.connection+', coverage '+x.coverage)
      ),'No limitations were returned for this snapshot. This does not verify devices or activity outside the included records.')},
      {type:'md',h:'Sources and versions',body:list(Object.keys(r.dataSources).map(k=>k+': '+r.dataSources[k]).concat(r.modelVersions.findings.length?['Model versions in findings: '+r.modelVersions.findings.join(', ')]:[]).concat(r.modelVersions.agentEngines.length?['Agents: '+r.modelVersions.agentEngines.join(', ')]:[]),'No data in this period.')},
      {type:'md',h:'Snapshot',body:'SHA-256 of this report\'s snapshot: '+d.snapshotHash+(d.signature?('\nSigned with key '+d.signature.keyId+'; the public key and signature are in the exported data.'):'\nNot signed: no signing key is configured on the server.')}
    ];
    renderDoc(true);
    reports.unshift([currentReport.title+' — '+now.toLocaleDateString(undefined,{month:'short',day:'numeric'}), currentReport.id, r.findings.some(f=>f.severity==='critical')?'crit':(r.findings.length?'high':'low'), 'ready', 'this session', structuredClone(currentReport), structuredClone(sections)]);
    renderList(0); reportsKpis();
    if(CF.toast) CF.toast('Evidence report ready — Export PDF to save','ok');
  }catch(e){
    setDocStatus('The evidence report could not be built',String((e&&e.message)||e));
  }
  genBtn.disabled=false;genBtn.classList.remove('busy');
}

